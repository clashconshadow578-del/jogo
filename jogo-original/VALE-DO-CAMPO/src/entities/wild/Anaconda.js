function anaNear(x, y, r) {
  const tx = Math.floor(x / TS),
    ty = Math.floor(y / TS);
  for (let dy = -r; dy <= r; dy++)
    for (let dx = -r; dx <= r; dx++) {
      const X = tx + dx,
        Y = ty + dy;
      if (X < 0 || Y < 0 || X >= MW || Y >= MH) continue;
      if (ground[Y * MW + X] === WATER) return true;
    }
  return false;
}

